/**
 * Helper to match query against Kerala dataset
 */
export function searchKeralaPlaces(query, limit = 5) {
  if (!query || query.trim().length < 2) return [];

  const q = query.trim().toLowerCase();

  const matches = KERALA_PLACES.filter(item => {
    const nameMatch = item.name.toLowerCase().includes(q);
    const cityMatch = item.city.toLowerCase().includes(q);
    const districtMatch = item.district.toLowerCase().includes(q);
    return nameMatch || cityMatch || districtMatch;
  });

  return matches.slice(0, limit).map((item, idx) => ({
    id: `kerala-local-${idx}-${item.name.replace(/\s+/g, '-').toLowerCase()}`,
    displayName: `${item.name}, ${item.city}, ${item.district}, Kerala`,
    name: item.name,
    lat: item.lat,
    lng: item.lng,
    city: item.city,
    district: item.district,
    state: 'Kerala',
    country: 'India',
    isKeralaPreset: true,
    category: item.category
  }));
}
